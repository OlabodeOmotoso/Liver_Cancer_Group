plot(d$PC1,d$PC2,col=cols[d$Synthetic_stratum],pch=19,xlab="PC1",ylab="PC2",main="Synthetic genotype structure (training only)")
legend("topright",legend=names(cols),col=cols,pch=19,bty="n")
